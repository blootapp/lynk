/** Inline SVG markup for an icon; stroke width is set in CSS (.ic). */
export function icon(name, size = 16) {
  return `<svg class="ic" width="${size}" height="${size}" viewBox="0 0 24 24" aria-hidden="true">${PATHS[name] ?? ''}</svg>`
}

/** Replaces every <i data-icon="name" data-size="N"> placeholder under root. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach(i => {
    i.outerHTML = icon(i.dataset.icon, Number(i.dataset.size) || 16)
  })
}
